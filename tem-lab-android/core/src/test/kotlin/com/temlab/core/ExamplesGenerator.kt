/** Writes worked examples (images + tables + a markdown summary) to docs/examples. */
class ExamplesGenerator {
    private val dir = File(System.getProperty("temlab.examples", "build/examples")).also { it.mkdirs() }

    private fun grey(p: FloatArray, w: Int, h: Int, lo: Float? = null, hi: Float? = null): BufferedImage {
        val a = lo ?: p.min(); val b = hi ?: p.max(); val r = if (b > a) b - a else 1f
        val img = BufferedImage(w, h, BufferedImage.TYPE_INT_RGB)
        for (i in p.indices) { val g = (((p[i] - a) / r).coerceIn(0f, 1f) * 255).toInt(); img.setRGB(i % w, i / w, (g shl 16) or (g shl 8) or g) }
        return img
    }
    private fun pct(p: FloatArray, q: Double) = p.sortedArray()[((p.size - 1) * q).toInt()]

    @Test fun generate() {
        val md = StringBuilder("# Worked examples (generated by `ExamplesGenerator`)\n\nAll inputs are synthetic images with exactly known content, so every number below can be checked against ground truth.\n\n")

        // ---- 1. FFT + interplanar distances
        val truth = listOf(Synthetic.Fringe(0.2355, 20.0), Synthetic.Fringe(0.2039, 74.74, 0.7))
        val lat = Synthetic.lattice(512, 512, 0.0189, 0.0189, truth, noise = 0.6)
        ImageIO.write(grey(lat.pixels, 512, 512), "png", File(dir, "01_hrtem_input.png"))
        val fft = FftAnalysis.compute(lat, SquareRoi(128, 128, 256), FftOptions(hannWindow = true, paddedSize = 1024))
        val refl = truth.mapIndexed { i, f -> val a = Math.toRadians(f.angleDeg); val (u, v) = fft.toFftPixel(cos(a) / f.dNm, -sin(a) / f.dNm); FftAnalysis.locatePeak(fft, u, v, id = i + 1)!! }
        val mate = run { val a = Math.toRadians(200.0); val (u, v) = fft.toFftPixel(cos(a) / 0.2355, -sin(a) / 0.2355); FftAnalysis.locatePeak(fft, u, v, id = 3)!! }
        val pair = FftAnalysis.symmetricPair(fft, refl[0], mate)
        val disp = fft.display(SpectrumScale.AMPLITUDE, true).let { arr -> FloatArray(arr.size) { arr[it] } }
        val fimg = grey(disp, fft.n, fft.n, pct(disp, 0.5), pct(disp, 0.9995))
        val crop = fimg.getSubimage(fft.n / 2 - 160, fft.n / 2 - 160, 320, 320)
        val big = BufferedImage(640, 640, BufferedImage.TYPE_INT_RGB)
        big.createGraphics().apply {
            setRenderingHint(RenderingHints.KEY_ANTIALIASING, RenderingHints.VALUE_ANTIALIAS_ON)
            drawImage(crop, 0, 0, 640, 640, null)
            font = Font("SansSerif", Font.BOLD, 18); stroke = BasicStroke(2f)
            for (r in refl + mate) {
                val x = ((r.u - (fft.n / 2 - 160)) * 2).toInt(); val y = ((r.v - (fft.n / 2 - 160)) * 2).toInt()
                color = Color(255, 213, 79); drawOval(x - 12, y - 12, 24, 24)
                drawString(String.format(Locale.US, "#%d d=%.4f nm", r.id, r.d), x + 14, y - 8)
            }
            color = Color.CYAN; drawOval(320 - 6, 320 - 6, 12, 12)
        }
        ImageIO.write(big, "png", File(dir, "02_fft_annotated.png"))
        File(dir, "02_fft_reflections.csv").outputStream().use { CsvWriter.write(Tables.reflections(refl + mate, "nm", 1.0), it) }
        md.append("## 1. Interactive FFT – interplanar distances\n\n![input](01_hrtem_input.png) ![fft](02_fft_annotated.png)\n\n")
        md.append("Synthetic Au-like HRTEM image, pixel 0.0189 nm, ROI 256×256 px, Hann window, zero-padded to 1024.\n\n| Reflection | True d (nm) | Measured d (nm) | Error |\n|---|---|---|---|\n")
        listOf(refl[0] to 0.2355, refl[1] to 0.2039, mate to 0.2355).forEach { (r, t) -> md.append(String.format(Locale.US, "| #%d | %.4f | %.5f | %+.3f %% |\n", r.id, t, r.d, (r.d - t) / t * 100)) }
        md.append(String.format(Locale.US, "\nSymmetric pair #1/#3: d = %.5f nm (Δd between the two = %.3f %%, origin offset %.3f px).  \nAngle #1–#2: %.2f° (true 54.74°).\n\n", pair.dMean, pair.dDifferencePercent, pair.originOffsetPx, FftAnalysis.angleBetween(refl[0], refl[1])))

        // ---- 2. Particles + histogram
        val rnd = java.util.Random(11)
        val blobs = (0 until 64).map { val r = 6 + rnd.nextDouble() * 8; Synthetic.Blob(24 + (it % 8) * 40.0, 24 + (it / 8) * 40.0, r, r) }
        val pim = Synthetic.particles(340, 340, blobs, pixelNm = 1.0)
        val set = ParticleSet(pim).also { it.segment(SegmentationParams(watershed = true)) }
        val ov = grey(pim.pixels, 340, 340)
        ov.createGraphics().apply {
            setRenderingHint(RenderingHints.KEY_ANTIALIASING, RenderingHints.VALUE_ANTIALIAS_ON)
            font = Font("SansSerif", Font.BOLD, 10)
            for (p in set.particles) {
                color = if (p.included) Color(80, 220, 120) else Color(230, 80, 80)
                val xs = p.contour.map { it.first.toInt() }.toIntArray(); val ys = p.contour.map { it.second.toInt() }.toIntArray()
                drawPolygon(xs, ys, xs.size)
                color = Color.YELLOW; p.measurement?.let { drawString("${p.id}", it.centroidX.toInt() - 4, it.centroidY.toInt() + 4) }
            }
        }
        ImageIO.write(ov, "png", File(dir, "03_particles_numbered.png"))
        val ecd = set.values(ParticleVariable.ECD)
        val fit = Statistics.lognormal(ecd)
        val ds = Statistics.describe(ecd)
        File(dir, "04_histogram_ecd.svg").writeText(SvgHistogram.render(Statistics.histogram(ecd, 8), "Particle size distribution", "Equivalent circular diameter (nm)", false, fit, ds.mean, ds.median))
        File(dir, "04_particles.csv").outputStream().use { CsvWriter.write(Tables.particles(set), it) }
        val truthD = Statistics.describe(blobs.map { 2 * it.rx }.toDoubleArray())
        md.append("## 2. Particle segmentation and histogram\n\n![particles](03_particles_numbered.png)\n\n![histogram](04_histogram_ecd.svg)\n\n")
        md.append(String.format(Locale.US, "64 disks with diameters drawn uniformly in 12–28 nm (pixel 1 nm), Otsu + watershed.\n\n| | Ground truth | Measured |\n|---|---|---|\n| N | 64 | %d |\n| Mean ECD (nm) | %.3f | %.3f |\n| SD (nm) | %.3f | %.3f |\n| Median (nm) | %.3f | %.3f |\n\nTable: [04_particles.csv](04_particles.csv)\n\n",
            set.included.size, truthD.mean, ds.mean, truthD.sd, ds.sd, truthD.median, ds.median))

        // ---- 3. Fourier filtering / IFFT
        val f1 = Synthetic.Fringe(0.32, 15.0); val f2 = Synthetic.Fringe(0.20, 75.0)
        val mix = Synthetic.lattice(256, 256, 0.02, 0.02, listOf(f1, f2), noise = 0.8)
        val a = Math.toRadians(f1.angleDeg); val k = 256 * 0.02
        val res = FourierFilter.apply(mix, SquareRoi(0, 0, 256), FourierMask(listOf(MaskShape.Circle(cos(a) / f1.dNm * k, -sin(a) / f1.dNm * k, 6.0, 2.0)), symmetric = true))
        val row = BufferedImage(256 * 3 + 20, 256, BufferedImage.TYPE_INT_RGB)
        row.createGraphics().apply {
            drawImage(grey(mix.pixels, 256, 256), 0, 0, null)
            drawImage(grey(res.mask, 256, 256, 0f, 1f), 266, 0, null)
            drawImage(grey(res.reconstruction.pixels, 256, 256), 532, 0, null)
            color = Color.YELLOW; font = Font("SansSerif", Font.BOLD, 13)
            drawString("original (2 lattices + noise)", 6, 16); drawString("mask (±g, symmetric)", 272, 16); drawString("IFFT – FILTERED", 538, 16)
        }
        ImageIO.write(row, "png", File(dir, "05_ifft_comparison.png"))
        val fftRec = FftAnalysis.compute(res.reconstruction, SquareRoi(0, 0, 256), FftOptions(paddedSize = 1024))
        val (u, v) = fftRec.toFftPixel(cos(a) / f1.dNm, -sin(a) / f1.dNm)
        md.append("## 3. Fourier filtering and IFFT\n\n![ifft](05_ifft_comparison.png)\n\n")
        md.append(String.format(Locale.US, "Mask around the 0.32 nm reflection (plus its automatic Friedel mate). Imaginary residual of the inverse transform: %.1e (Hermitian symmetry preserved). d measured on the reconstruction: %.4f nm (true 0.32 nm). Mask: `%s`.\n",
            res.imaginaryResidual, FftAnalysis.locatePeak(fftRec, u, v)!!.d, res.description))
        File(dir, "README.md").writeText(md.toString())
    }
}
